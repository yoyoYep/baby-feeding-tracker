function getPercentile(value, monthAge, gender, metric) {
  let data
  if (metric === 'weight') data = gender === 'male' ? weightBoys : weightGirls
  else if (metric === 'length') data = gender === 'male' ? lengthBoys : lengthGirls
  else data = gender === 'male' ? hcBoys : hcGirls

  const month = Math.min(Math.round(monthAge), 24)

  if (value <= data.P3[month]) return { percentile: 3, label: '<P3' }
  if (value <= data.P15[month]) return { percentile: 10, label: 'P3~P15' }
  if (value <= data.P50[month]) return { percentile: 35, label: 'P15~P50' }
  if (value <= data.P85[month]) return { percentile: 65, label: 'P50~P85' }
  if (value <= data.P97[month]) return { percentile: 90, label: 'P85~P97' }
  return { percentile: 99, label: '>P97' }
}

function getRefData(gender, metric) {
  if (metric === 'weight') return gender === 'male' ? weightBoys : weightGirls
  if (metric === 'length') return gender === 'male' ? lengthBoys : lengthGirls
  return gender === 'male' ? hcBoys : hcGirls
}

